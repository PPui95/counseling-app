  const score = answers.reduce((sum, a) => sum + (a + 1), 0);
  if (score <= 9) return { score, level: 'ต่ำมาก', color: '#E53935', interpretation: 'ไม่พึงพอใจในชีวิตอย่างมาก ควรขอความช่วยเหลือ' };
  if (score <= 14) return { score, level: 'ต่ำ', color: '#FF7043', interpretation: 'ไม่พึงพอใจในชีวิต แนะนำให้ปรึกษาผู้เชี่ยวชาญ' };
  if (score <= 19) return { score, level: 'ปานกลาง-ต่ำ', color: '#FFA726', interpretation: 'ค่อนข้างไม่พึงพอใจในชีวิต' };
  if (score <= 24) return { score, level: 'ปานกลาง', color: '#AED581', interpretation: 'พึงพอใจในชีวิตในระดับปานกลาง' };
